"""R (tidyverse) and SQL equivalents for the core analysis components.

R scripts target readr/dplyr/ggplot2. SQL is plain ANSI-style and runs on SQLite/DuckDB/Postgres
(table name defaults to ``data``). Components without an equivalent return ``None``.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any


def _r(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _ident(s: str) -> str:
    return '"' + s.replace('"', '""') + '"'


def _r_head(title: str, filename: str, libs: Sequence[str] = ("readr", "dplyr", "ggplot2")) -> str:
    reader = "read_csv" if not filename.lower().endswith(".parquet") else "read_csv"
    return (
        f"# {title}\n# Generated by CelestiusAI. Run in RStudio or Google Colab (R runtime).\n"
        + "".join(f"library({lib})\n" for lib in libs)
        + f"\ndf <- {reader}({_r(filename)})\nglimpse(df)\n\n"
    )


# --------------------------------------------------------------------------- R
def r_profile(filename: str, **_: Any) -> str:
    return (
        _r_head("Dataset profile", filename, ("readr", "dplyr", "tidyr", "skimr"))
        + """# Missing values per column
df %>% summarise(across(everything(), ~ sum(is.na(.)))) %>%
  pivot_longer(everything(), names_to = "column", values_to = "missing") %>%
  mutate(missing_pct = round(missing / nrow(df) * 100, 2)) %>%
  arrange(desc(missing))

# Exact duplicate rows
cat("Duplicate rows:", sum(duplicated(df)), "\\n")

# Summary statistics
skim(df)
"""
    )


def r_missing(filename: str, **_: Any) -> str:
    return (
        _r_head("Missing values", filename, ("readr", "dplyr", "tidyr", "ggplot2"))
        + """missing <- df %>%
  summarise(across(everything(), ~ mean(is.na(.)) * 100)) %>%
  pivot_longer(everything(), names_to = "column", values_to = "missing_pct") %>%
  arrange(desc(missing_pct))
print(missing)

ggplot(missing, aes(x = reorder(column, -missing_pct), y = missing_pct)) +
  geom_col(fill = "steelblue") +
  labs(title = "Missing % by column", x = NULL, y = "missing %") +
  theme(axis.text.x = element_text(angle = 45, hjust = 1))
"""
    )


def r_duplicates(filename: str, subset: Sequence[str] | None = None, **_: Any) -> str:
    cols = ", ".join(subset) if subset else "everything()"
    return (
        _r_head("Duplicates", filename)
        + f"""dups <- df %>% group_by(across({cols})) %>% filter(n() > 1) %>% ungroup()
cat("Rows involved in duplicates:", nrow(dups), "\\n")
head(dups, 20)
"""
    )


def r_outliers(filename: str, column: str, **_: Any) -> str:
    return (
        _r_head(f"Outliers in {column} (IQR)", filename)
        + f"""x <- df[[{_r(column)}]]
q <- quantile(x, c(0.25, 0.75), na.rm = TRUE)
iqr <- q[2] - q[1]
lower <- q[1] - 1.5 * iqr
upper <- q[2] + 1.5 * iqr
outliers <- df %>% filter(.data[[{_r(column)}]] < lower | .data[[{_r(column)}]] > upper)
cat(nrow(outliers), "outliers outside [", lower, ",", upper, "]\\n")

ggplot(df, aes(y = .data[[{_r(column)}]])) + geom_boxplot(fill = "steelblue") +
  labs(title = {_r(column + " - box plot")})
"""
    )


def r_distribution(filename: str, column: str, numeric: bool = True, **_: Any) -> str:
    if numeric:
        return (
            _r_head(f"Distribution of {column}", filename)
            + f"""summary(df[[{_r(column)}]])
ggplot(df, aes(x = .data[[{_r(column)}]])) +
  geom_histogram(bins = 30, fill = "steelblue", colour = "white") +
  labs(title = {_r("Distribution of " + column)})
shapiro.test(sample(na.omit(df[[{_r(column)}]]), min(5000, sum(!is.na(df[[{_r(column)}]])))))
"""
        )
    return (
        _r_head(f"Categories of {column}", filename)
        + f"""counts <- df %>% count(.data[[{_r(column)}]], sort = TRUE) %>% head(20)
print(counts)
ggplot(counts, aes(x = reorder(.data[[{_r(column)}]], -n), y = n)) + geom_col(fill = "steelblue") +
  labs(title = {_r("Top categories of " + column)}, x = NULL)
"""
    )


def r_correlation(filename: str, columns: Sequence[str], method: str = "pearson", **_: Any) -> str:
    cols = ", ".join(_r(c) for c in columns)
    return (
        _r_head(
            f"{method.capitalize()} correlation", filename, ("readr", "dplyr", "ggplot2", "tidyr")
        )
        + f"""num <- df %>% select(all_of(c({cols})))
corr <- cor(num, use = "pairwise.complete.obs", method = {_r(method)})
print(round(corr, 2))

corr_long <- as.data.frame(as.table(corr))
ggplot(corr_long, aes(Var1, Var2, fill = Freq)) + geom_tile() +
  scale_fill_gradient2(low = "firebrick", mid = "white", high = "steelblue", limits = c(-1, 1)) +
  geom_text(aes(label = round(Freq, 2))) + labs(title = {_r(method.capitalize() + " correlation")}, x = NULL, y = NULL)
"""
    )


def r_grouped(filename: str, group_col: str, measure: str, agg: str = "mean", **_: Any) -> str:
    fn = {
        "mean": "mean",
        "median": "median",
        "sum": "sum",
        "min": "min",
        "max": "max",
        "std": "sd",
        "count": "length",
    }.get(agg, "mean")
    return (
        _r_head(f"{agg} of {measure} by {group_col}", filename)
        + f"""summary <- df %>%
  group_by(.data[[{_r(group_col)}]]) %>%
  summarise(value = {fn}(.data[[{_r(measure)}]], na.rm = TRUE), n = n()) %>%
  arrange(desc(value))
print(summary)

ggplot(summary, aes(x = reorder(.data[[{_r(group_col)}]], -value), y = value)) + geom_col(fill = "steelblue") +
  labs(title = {_r(f"{agg} of {measure} by {group_col}")}, x = {_r(group_col)}, y = {_r(agg)})
"""
    )


def r_crosstab(filename: str, col_a: str, col_b: str, **_: Any) -> str:
    return (
        _r_head(f"Association: {col_a} x {col_b}", filename)
        + f"""tab <- table(df[[{_r(col_a)}]], df[[{_r(col_b)}]])
print(tab)
print(round(prop.table(tab, 1), 3))
test <- chisq.test(tab)
print(test)
cat("Cramer's V:", sqrt(unname(test$statistic) / (sum(tab) * (min(dim(tab)) - 1))), "\\n")
"""
    )


# --------------------------------------------------------------------------- SQL
def sql_profile(table: str, columns: Sequence[str], **_: Any) -> str:
    t = _ident(table)
    parts = ",\n  ".join(
        f"SUM(CASE WHEN {_ident(c)} IS NULL THEN 1 ELSE 0 END) AS {_ident(c + '__missing')}"
        for c in columns
    )
    return f"""-- Row count and missing values per column
SELECT
  COUNT(*) AS total_rows,
  {parts}
FROM {t};
"""


def sql_duplicates(table: str, columns: Sequence[str], **_: Any) -> str:
    cols = ", ".join(_ident(c) for c in columns)
    return f"""-- Rows that share the same values in the chosen columns
SELECT {cols}, COUNT(*) AS copies
FROM {_ident(table)}
GROUP BY {cols}
HAVING COUNT(*) > 1
ORDER BY copies DESC;
"""


def sql_grouped(table: str, group_col: str, measure: str, agg: str = "mean", **_: Any) -> str:
    fn = {"mean": "AVG", "sum": "SUM", "min": "MIN", "max": "MAX", "count": "COUNT"}.get(agg, "AVG")
    return f"""-- {agg} of {measure} by {group_col}
SELECT {_ident(group_col)} AS grp,
       {fn}({_ident(measure)}) AS value,
       COUNT(*) AS n
FROM {_ident(table)}
GROUP BY {_ident(group_col)}
ORDER BY value DESC;
"""


def sql_top_categories(table: str, column: str, limit: int = 20, **_: Any) -> str:
    return f"""-- Most frequent values of {column}
SELECT {_ident(column)} AS value, COUNT(*) AS n,
       ROUND(100.0 * COUNT(*) / (SELECT COUNT(*) FROM {_ident(table)}), 2) AS pct
FROM {_ident(table)}
GROUP BY {_ident(column)}
ORDER BY n DESC
LIMIT {int(limit)};
"""


def sql_time_trend(table: str, date_col: str, measure: str, freq: str = "month", **_: Any) -> str:
    fmt = {"day": "%Y-%m-%d", "month": "%Y-%m", "year": "%Y"}.get(freq, "%Y-%m")
    return f"""-- {measure} per {freq} (SQLite strftime; use date_trunc in Postgres/DuckDB)
SELECT strftime('{fmt}', {_ident(date_col)}) AS period,
       AVG({_ident(measure)}) AS avg_value,
       COUNT(*) AS n
FROM {_ident(table)}
WHERE {_ident(date_col)} IS NOT NULL
GROUP BY period
ORDER BY period;
"""
