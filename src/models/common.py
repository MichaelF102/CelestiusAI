"""Pydantic foundation models for datasets, analysis steps, plans, and evidence-backed findings."""

from datetime import UTC, datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

FindingImportance = Literal["low", "medium", "high", "critical"]
StepStatus = Literal["pending", "running", "completed", "failed", "skipped"]


class DatasetMetadata(BaseModel):
    """Metadata describing an ingested tabular dataset."""

    model_config = ConfigDict(frozen=True)

    filename: str = Field(..., min_length=1, description="Original filename of the dataset.")
    file_format: str = Field(..., min_length=1, description="File extension or detected format.")
    row_count: int = Field(..., ge=0, description="Total number of rows.")
    column_count: int = Field(..., ge=0, description="Total number of columns.")
    dataset_id: str | None = Field(default=None, description="Optional unique identifier.")
    file_size_bytes: int | None = Field(
        default=None, ge=0, description="File size in bytes if available."
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Timestamp when dataset was ingested.",
    )


class AnalysisFinding(BaseModel):
    """Structured analytical finding aligned with the 6-layer interpretation framework."""

    title: str = Field(..., min_length=1, description="Concise headline of the finding.")
    summary: str = Field(..., min_length=1, description="Detailed explanatory narrative.")
    severity_or_importance: FindingImportance = Field(
        default="medium",
        description="Business impact or statistical severity level.",
    )
    evidence_references: list[str] = Field(
        default_factory=list,
        description="References to verified metrics, tables, or chart IDs supporting the claim.",
    )
    limitations: list[str] = Field(
        default_factory=list,
        description="Assumptions, sample size warnings, or potential confounding factors.",
    )
    suggested_follow_up: list[str] = Field(
        default_factory=list,
        description="Actionable next investigations or business decisions.",
    )


class AnalysisStep(BaseModel):
    """Single analytical action in an investigation workflow."""

    step_id: str = Field(..., min_length=1, description="Unique identifier for the step.")
    tool_name: str = Field(..., min_length=1, description="Deterministic analytical tool name.")
    purpose: str = Field(..., min_length=1, description="Reason for executing this tool.")
    status: StepStatus = Field(default="pending", description="Current step execution state.")
    result_reference: str | None = Field(
        default=None, description="Key or ID referencing computed tool results."
    )
    execution_time_seconds: float | None = Field(
        default=None, ge=0.0, description="Measured execution duration."
    )


class AnalysisPlan(BaseModel):
    """Ordered multi-step analytical plan generated by the planning engine."""

    objective: str = Field(
        ..., min_length=1, description="The research question or business objective."
    )
    steps: list[AnalysisStep] = Field(
        default_factory=list, description="Ordered sequence of analytical steps."
    )
    expected_outputs: list[str] = Field(
        default_factory=list,
        description="List of target insights or artifacts expected from this plan.",
    )
